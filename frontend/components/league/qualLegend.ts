/** 色值 → 图例文字。联赛或颜色未配置时回落"晋级区"。 */
export function qualLabel(leagueId: number | string | null | undefined, color: string): string {
  const id = typeof leagueId === "string" ? Number(leagueId) : leagueId;
  const table = id != null && Number.isFinite(id) ? QUAL_LEGEND[id] : undefined;
  return table?.[color.toLowerCase()] ?? QUAL_FALLBACK;
}
