def reader_text(value):
    text=str(value)
    if text in LABELS:return LABELS[text]
    for key in ('captured_pre_match','current_postmatch','reconstructed'):
        text=text.replace(key,LABELS[key])
    text=re.sub(r'同一历史样本中，两份名单直接创造或终结的机会覆盖为 (\d+) → (\d+) / (\d+) 次',
                r'在同一批历史比赛中，预计首发名单参与最后一传或射门\1次，正式首发名单\2次；这些比赛共\3次射门',text)
    text=re.sub(r'曾直接创造或终结 (\d+) 条机会',r'曾参与\1次射门的最后一传或终结',text)
    for before,after in PHRASES:text=text.replace(before,after)
    text=re.sub(r'阶段\s*([1-4])(?=\s)',lambda m:{'1':'上半场','2':'下半场','3':'加时上半场','4':'加时下半场'}[m[1]],text)
    text=re.sub(r'xG（覆盖\s*(\d+)/(\d+)）',r'xG（\2次射门中\1次有xG数据）',text)
    text=text.replace('整场口径','按整场统计').replace('同一口径','相同统计条件')
    text=re.sub(r'(在所选比赛中的出场时间不足\s*\d+(?:\.\d+)?)(?![\d.])(?=[，。；])',r'\1分钟',text)
    return text


